import { randomUUID } from 'crypto';
import { Person } from '../types/person';
import { Relationship } from '../types/relationship';
import { FamilyRepository } from '../repositories/family.repository';
import { LocalJsonFamilyRepository } from '../repositories/local-json.repository';
import { CreatePersonSchema, UpdatePersonSchema } from '../validators/person.validator';
import { ValidationError, NotFoundError, ConflictError } from './errors';
import { FamilyValidationError } from '../validators/family.validator';

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export class PersonService {
  private repository: FamilyRepository;

  constructor(repository?: FamilyRepository) {
    this.repository = repository || new LocalJsonFamilyRepository();
  }

  /**
   * Creates a new person and any initial parent/spouse relationships atomically.
   */
  async createPerson(input: unknown): Promise<Person> {
    // 1. Requirement 6: Generate UUIDs on backend. Never accept a client-supplied ID.
    if (typeof input === 'object' && input !== null && 'id' in input && (input as any).id !== undefined) {
      throw new ValidationError(
        'CLIENT_ID_NOT_ALLOWED',
        'Client-supplied ID is not allowed during person creation. IDs are generated by the server.'
      );
    }

    // 2. Validate input schema with Zod
    const parseResult = CreatePersonSchema.safeParse(input);
    if (!parseResult.success) {
      throw new ValidationError(
        'INVALID_PERSON_INPUT',
        parseResult.error.issues.map((i) => i.message).join('; '),
        parseResult.error.issues
      );
    }

    const data = parseResult.data;

    // 3. Load current data and version
    const allPersons = await this.repository.getAllPersons(true);
    const allRelationships = await this.repository.getAllRelationships();
    const version = await this.repository.getVersion();

    // 4. Validate referenced relatives if provided
    if (data.father_id) {
      const father = allPersons.find((p) => p.id === data.father_id);
      if (!father) {
        throw new NotFoundError('FATHER_NOT_FOUND', `Father with ID "${data.father_id}" was not found.`);
      }
      if (father.is_archived) {
        throw new ValidationError('CANNOT_LINK_ARCHIVED_PARENT', 'Cannot connect to an archived father.');
      }
    }

    if (data.mother_id) {
      const mother = allPersons.find((p) => p.id === data.mother_id);
      if (!mother) {
        throw new NotFoundError('MOTHER_NOT_FOUND', `Mother with ID "${data.mother_id}" was not found.`);
      }
      if (mother.is_archived) {
        throw new ValidationError('CANNOT_LINK_ARCHIVED_PARENT', 'Cannot connect to an archived mother.');
      }
    }

    if (data.father_id && data.mother_id && data.father_id === data.mother_id) {
      throw new ValidationError('SAME_PARENTS', 'Father and mother cannot be the same person.');
    }

    if (data.spouse_id) {
      const spouse = allPersons.find((p) => p.id === data.spouse_id);
      if (!spouse) {
        throw new NotFoundError('SPOUSE_NOT_FOUND', `Spouse with ID "${data.spouse_id}" was not found.`);
      }
      if (spouse.is_archived) {
        throw new ValidationError('CANNOT_LINK_ARCHIVED_SPOUSE', 'Cannot connect to an archived spouse.');
      }
    }

    // 5. Construct new person
    const personId = randomUUID();
    const now = new Date().toISOString();
    const isLiving = data.is_living !== undefined ? data.is_living : data.death_date ? false : true;

    const newPerson: Person = {
      id: personId,
      first_name: data.first_name,
      middle_name: data.middle_name ?? null,
      last_name: data.last_name ?? null,
      alias: data.alias ?? null,
      gender: data.gender,
      birth_date: data.birth_date ?? null,
      death_date: data.death_date ?? null,
      birth_place: data.birth_place ?? null,
      death_place: data.death_place ?? null,
      profile_photo: data.profile_photo ?? null,
      biography: data.biography ?? '',
      is_living: isLiving,
      is_archived: false,
      created_at: now,
      updated_at: now,
      archived_at: null,
    };

    // 6. Build relationships to be created as part of the same logical operation
    const newRelationships: Relationship[] = [];

    if (data.father_id) {
      newRelationships.push({
        id: randomUUID(),
        person_id: personId, // child
        related_person_id: data.father_id, // parent
        relationship_type: 'parent',
        parent_type: 'biological',
        start_date: null,
        end_date: null,
        notes: null,
        created_at: now,
      });
    }

    if (data.mother_id) {
      newRelationships.push({
        id: randomUUID(),
        person_id: personId, // child
        related_person_id: data.mother_id, // parent
        relationship_type: 'parent',
        parent_type: 'biological',
        start_date: null,
        end_date: null,
        notes: null,
        created_at: now,
      });
    }

    if (data.spouse_id) {
      newRelationships.push({
        id: randomUUID(),
        person_id: personId,
        related_person_id: data.spouse_id,
        relationship_type: 'spouse',
        parent_type: null,
        start_date: null,
        end_date: null,
        notes: null,
        created_at: now,
      });
    }

    // 7. Atomic save with optimistic locking & full graph validation
    try {
      await this.repository.saveFamilyData(
        [...allPersons, newPerson],
        [...allRelationships, ...newRelationships],
        version
      );
    } catch (err: any) {
      if (err instanceof FamilyValidationError) {
        throw new ConflictError(err.code, err.message, err.details);
      }
      throw err;
    }

    return newPerson;
  }

  /**
   * Retrieves all persons, optionally including archived records and searching by query.
   */
  async getAllPersons(options?: { includeArchived?: boolean; search?: string }): Promise<Person[]> {
    const includeArchived = options?.includeArchived === true;
    let persons = await this.repository.getAllPersons(includeArchived);

    if (options?.search && options.search.trim().length > 0) {
      const q = options.search.trim().toLowerCase();
      persons = persons.filter((p) => {
        const fullName = `${p.first_name} ${p.middle_name || ''} ${p.last_name || ''}`.toLowerCase();
        return (
          p.first_name.toLowerCase().includes(q) ||
          (p.middle_name && p.middle_name.toLowerCase().includes(q)) ||
          (p.last_name && p.last_name.toLowerCase().includes(q)) ||
          (p.alias && p.alias.toLowerCase().includes(q)) ||
          fullName.includes(q)
        );
      });
    }

    return persons;
  }

  /**
   * Retrieves a single person by their permanent UUID.
   */
  async getPersonById(id: string, options?: { includeArchived?: boolean }): Promise<Person> {
    if (!UUID_REGEX.test(id)) {
      throw new ValidationError('INVALID_UUID', `Person ID "${id}" is not a valid UUID.`);
    }

    const person = await this.repository.getPersonById(id);
    if (!person) {
      throw new NotFoundError('PERSON_NOT_FOUND', `Person with ID "${id}" was not found.`);
    }

    if (person.is_archived && !options?.includeArchived) {
      throw new NotFoundError(
        'PERSON_ARCHIVED',
        `Person with ID "${id}" is archived. Pass includeArchived=true to retrieve archived records.`
      );
    }

    return person;
  }

  /**
   * Updates personal details without modifying ID or relationships.
   */
  async updatePerson(id: string, input: unknown): Promise<Person> {
    if (!UUID_REGEX.test(id)) {
      throw new ValidationError('INVALID_UUID', `Person ID "${id}" is not a valid UUID.`);
    }

    // Verify client is not trying to change ID
    if (typeof input === 'object' && input !== null && 'id' in input && (input as any).id !== undefined) {
      if ((input as any).id !== id) {
        throw new ValidationError('CANNOT_CHANGE_ID', 'Person ID is permanent and cannot be modified.');
      }
    }

    const parseResult = UpdatePersonSchema.safeParse(input);
    if (!parseResult.success) {
      throw new ValidationError(
        'INVALID_UPDATE_INPUT',
        parseResult.error.issues.map((i) => i.message).join('; '),
        parseResult.error.issues
      );
    }

    const updates = parseResult.data;

    const allPersons = await this.repository.getAllPersons(true);
    const allRelationships = await this.repository.getAllRelationships();
    const version = await this.repository.getVersion();

    const personIndex = allPersons.findIndex((p) => p.id === id);
    if (personIndex === -1) {
      throw new NotFoundError('PERSON_NOT_FOUND', `Person with ID "${id}" was not found.`);
    }

    const existing = allPersons[personIndex];
    if (existing.is_archived) {
      throw new ConflictError('CANNOT_UPDATE_ARCHIVED_PERSON', 'Cannot update an archived person. Restore them first.');
    }

    // Calculate final living and death dates
    const finalIsLiving = updates.is_living !== undefined ? updates.is_living : existing.is_living;
    const finalDeathDate = updates.death_date !== undefined ? updates.death_date : existing.death_date;

    if (finalIsLiving && finalDeathDate !== null) {
      throw new ValidationError('LIVING_PERSON_CANNOT_HAVE_DEATH_DATE', 'A living person cannot have a death date.');
    }

    const updatedPerson: Person = {
      id: existing.id, // permanent
      first_name: updates.first_name ?? existing.first_name,
      middle_name: updates.middle_name !== undefined ? updates.middle_name : existing.middle_name,
      last_name: updates.last_name !== undefined ? updates.last_name : existing.last_name,
      alias: updates.alias !== undefined ? updates.alias : existing.alias,
      gender: updates.gender ?? existing.gender,
      birth_date: updates.birth_date !== undefined ? updates.birth_date : existing.birth_date,
      death_date: finalDeathDate,
      birth_place: updates.birth_place !== undefined ? updates.birth_place : existing.birth_place,
      death_place: updates.death_place !== undefined ? updates.death_place : existing.death_place,
      profile_photo: updates.profile_photo !== undefined ? updates.profile_photo : existing.profile_photo,
      biography: updates.biography !== undefined ? updates.biography : existing.biography,
      is_living: finalIsLiving,
      is_archived: existing.is_archived,
      created_at: existing.created_at,
      updated_at: new Date().toISOString(),
      archived_at: existing.archived_at,
    };

    const newPersons = [...allPersons];
    newPersons[personIndex] = updatedPerson;

    // Requirement 8: Updating personal information must never silently modify or delete relationships
    try {
      await this.repository.saveFamilyData(newPersons, allRelationships, version);
    } catch (err: any) {
      if (err instanceof FamilyValidationError) {
        throw new ConflictError(err.code, err.message, err.details);
      }
      throw err;
    }

    return updatedPerson;
  }

  /**
   * Archives a person, hiding them from default views while preserving all relationships.
   */
  async archivePerson(id: string): Promise<Person> {
    if (!UUID_REGEX.test(id)) {
      throw new ValidationError('INVALID_UUID', `Person ID "${id}" is not a valid UUID.`);
    }

    const allPersons = await this.repository.getAllPersons(true);
    const allRelationships = await this.repository.getAllRelationships();
    const version = await this.repository.getVersion();

    const personIndex = allPersons.findIndex((p) => p.id === id);
    if (personIndex === -1) {
      throw new NotFoundError('PERSON_NOT_FOUND', `Person with ID "${id}" was not found.`);
    }

    const existing = allPersons[personIndex];
    if (existing.is_archived) {
      throw new ConflictError('ALREADY_ARCHIVED', `Person with ID "${id}" is already archived.`);
    }

    const now = new Date().toISOString();
    const archivedPerson: Person = {
      ...existing,
      is_archived: true,
      archived_at: now,
      updated_at: now,
    };

    const newPersons = [...allPersons];
    newPersons[personIndex] = archivedPerson;

    try {
      await this.repository.saveFamilyData(newPersons, allRelationships, version);
    } catch (err: any) {
      if (err instanceof FamilyValidationError) {
        throw new ConflictError(err.code, err.message, err.details);
      }
      throw err;
    }

    return archivedPerson;
  }

  /**
   * Restores an archived person back into the active view.
   */
  async restorePerson(id: string): Promise<Person> {
    if (!UUID_REGEX.test(id)) {
      throw new ValidationError('INVALID_UUID', `Person ID "${id}" is not a valid UUID.`);
    }

    const allPersons = await this.repository.getAllPersons(true);
    const allRelationships = await this.repository.getAllRelationships();
    const version = await this.repository.getVersion();

    const personIndex = allPersons.findIndex((p) => p.id === id);
    if (personIndex === -1) {
      throw new NotFoundError('PERSON_NOT_FOUND', `Person with ID "${id}" was not found.`);
    }

    const existing = allPersons[personIndex];
    if (!existing.is_archived) {
      throw new ConflictError('NOT_ARCHIVED', `Person with ID "${id}" is not archived.`);
    }

    const now = new Date().toISOString();
    const restoredPerson: Person = {
      ...existing,
      is_archived: false,
      archived_at: null,
      updated_at: now,
    };

    const newPersons = [...allPersons];
    newPersons[personIndex] = restoredPerson;

    try {
      await this.repository.saveFamilyData(newPersons, allRelationships, version);
    } catch (err: any) {
      if (err instanceof FamilyValidationError) {
        throw new ConflictError(err.code, err.message, err.details);
      }
      throw err;
    }

    return restoredPerson;
  }
}
