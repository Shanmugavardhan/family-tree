import { randomUUID } from 'crypto';
import { Relationship } from '../types/relationship';
import { FamilyRepository } from '../repositories/family.repository';
import { LocalJsonFamilyRepository } from '../repositories/local-json.repository';
import { CreateRelationshipSchema, UpdateRelationshipSchema } from '../validators/relationship.validator';
import { ValidationError, NotFoundError, ConflictError } from './errors';
import { FamilyValidationError } from '../validators/family.validator';

const UUID_REGEX = /^[0-9a-f]{8}-[0-9a-f]{4}-[1-5][0-9a-f]{3}-[89ab][0-9a-f]{3}-[0-9a-f]{12}$/i;

export class RelationshipService {
  private repository: FamilyRepository;

  constructor(repository?: FamilyRepository) {
    this.repository = repository || new LocalJsonFamilyRepository();
  }

  /**
   * Creates a new parent or spouse relationship after strict validation.
   */
  async createRelationship(input: unknown): Promise<Relationship> {
    // 1. Reject client-supplied ID
    if (typeof input === 'object' && input !== null && 'id' in input && (input as any).id !== undefined) {
      throw new ValidationError(
        'CLIENT_ID_NOT_ALLOWED',
        'Client-supplied ID is not allowed during relationship creation. IDs are generated by the server.'
      );
    }

    // 2. Normalize potential field aliases (e.g. child_id/parent_id or spouse_id)
    let normalizedInput: any = input;
    if (typeof input === 'object' && input !== null) {
      normalizedInput = { ...input };
      if ('child_id' in normalizedInput && !('person_id' in normalizedInput)) {
        normalizedInput.person_id = normalizedInput.child_id;
      }
      if ('parent_id' in normalizedInput && !('related_person_id' in normalizedInput)) {
        normalizedInput.related_person_id = normalizedInput.parent_id;
        normalizedInput.relationship_type = normalizedInput.relationship_type || 'parent';
      }
      if ('spouse_id' in normalizedInput && !('related_person_id' in normalizedInput)) {
        normalizedInput.related_person_id = normalizedInput.spouse_id;
        normalizedInput.relationship_type = normalizedInput.relationship_type || 'spouse';
      }
    }

    // 3. Schema validation
    const parseResult = CreateRelationshipSchema.safeParse(normalizedInput);
    if (!parseResult.success) {
      throw new ValidationError(
        'INVALID_RELATIONSHIP_INPUT',
        parseResult.error.issues.map((i) => i.message).join('; '),
        parseResult.error.issues
      );
    }

    const data = parseResult.data;

    // 4. Load persons, relationships, and current storage version
    const allPersons = await this.repository.getAllPersons(true);
    const allRelationships = await this.repository.getAllRelationships();
    const version = await this.repository.getVersion();

    // 5. Verify person existence
    const person1 = allPersons.find((p) => p.id === data.person_id);
    if (!person1) {
      throw new NotFoundError('PERSON_NOT_FOUND', `Person with ID "${data.person_id}" was not found.`);
    }

    const person2 = allPersons.find((p) => p.id === data.related_person_id);
    if (!person2) {
      throw new NotFoundError(
        'RELATED_PERSON_NOT_FOUND',
        `Related person with ID "${data.related_person_id}" was not found.`
      );
    }

    // 6. Verify neither person is archived
    if (person1.is_archived || person2.is_archived) {
      throw new ValidationError(
        'CANNOT_LINK_ARCHIVED_PERSON',
        'Cannot create a relationship involving an archived person.'
      );
    }

    // 7. Verify no self-relations
    if (data.person_id === data.related_person_id) {
      throw new ValidationError(
        'SELF_RELATION_NOT_ALLOWED',
        'A person cannot have a relationship with themselves.'
      );
    }

    // 8. Prevent duplicate relationships
    if (data.relationship_type === 'parent') {
      const existingParent = allRelationships.find(
        (r) =>
          r.relationship_type === 'parent' &&
          r.person_id === data.person_id &&
          r.related_person_id === data.related_person_id
      );
      if (existingParent) {
        throw new ConflictError(
          'DUPLICATE_PARENT_RELATIONSHIP',
          `Person "${data.person_id}" already has parent "${data.related_person_id}".`
        );
      }
    }

    if (data.relationship_type === 'spouse') {
      // Spouse is symmetric: (A, B) or (B, A) are identical relationships
      const existingSpouse = allRelationships.find(
        (r) =>
          r.relationship_type === 'spouse' &&
          ((r.person_id === data.person_id && r.related_person_id === data.related_person_id) ||
            (r.person_id === data.related_person_id && r.related_person_id === data.person_id))
      );
      if (existingSpouse) {
        throw new ConflictError(
          'DUPLICATE_SPOUSE_RELATIONSHIP',
          'A spouse relationship already exists between these two persons.'
        );
      }
    }

    // 9. Construct new relationship
    const newRel: Relationship = {
      id: randomUUID(),
      person_id: data.person_id,
      related_person_id: data.related_person_id,
      relationship_type: data.relationship_type,
      parent_type: data.parent_type ?? null,
      start_date: data.start_date ?? null,
      end_date: data.end_date ?? null,
      notes: data.notes ?? null,
      created_at: new Date().toISOString(),
    };

    // 10. Atomic save with graph cycle detection and constraint validation
    try {
      await this.repository.saveFamilyData(allPersons, [...allRelationships, newRel], version);
    } catch (err: any) {
      if (err instanceof FamilyValidationError) {
        throw new ConflictError(err.code, err.message, err.details);
      }
      throw err;
    }

    return newRel;
  }

  /**
   * Retrieves all relationships, optionally filtered by personId or relationshipType.
   */
  async getAllRelationships(options?: {
    personId?: string;
    relationshipType?: string;
  }): Promise<Relationship[]> {
    let rels = await this.repository.getAllRelationships();

    if (options?.personId) {
      if (!UUID_REGEX.test(options.personId)) {
        throw new ValidationError('INVALID_UUID', `Person ID "${options.personId}" is not a valid UUID.`);
      }
      rels = rels.filter(
        (r) => r.person_id === options.personId || r.related_person_id === options.personId
      );
    }

    if (options?.relationshipType) {
      rels = rels.filter((r) => r.relationship_type === options.relationshipType);
    }

    return rels;
  }

  /**
   * Retrieves a single relationship by UUID.
   */
  async getRelationshipById(id: string): Promise<Relationship> {
    if (!UUID_REGEX.test(id)) {
      throw new ValidationError('INVALID_UUID', `Relationship ID "${id}" is not a valid UUID.`);
    }

    const rels = await this.repository.getAllRelationships();
    const rel = rels.find((r) => r.id === id);
    if (!rel) {
      throw new NotFoundError('RELATIONSHIP_NOT_FOUND', `Relationship with ID "${id}" was not found.`);
    }

    return rel;
  }

  /**
   * Updates editable metadata of a relationship without altering the graph edges.
   */
  async updateRelationship(id: string, input: unknown): Promise<Relationship> {
    if (!UUID_REGEX.test(id)) {
      throw new ValidationError('INVALID_UUID', `Relationship ID "${id}" is not a valid UUID.`);
    }

    if (typeof input === 'object' && input !== null) {
      if ('id' in input && (input as any).id !== id) {
        throw new ValidationError('CANNOT_CHANGE_ID', 'Relationship ID is permanent and cannot be modified.');
      }
      if ('person_id' in input || 'related_person_id' in input || 'relationship_type' in input) {
        throw new ValidationError(
          'CANNOT_CHANGE_RELATIONSHIP_PARTICIPANTS',
          'Connected persons and relationship type cannot be altered. Delete and create a new relationship instead.'
        );
      }
    }

    const parseResult = UpdateRelationshipSchema.safeParse(input);
    if (!parseResult.success) {
      throw new ValidationError(
        'INVALID_UPDATE_INPUT',
        parseResult.error.issues.map((i) => i.message).join('; '),
        parseResult.error.issues
      );
    }

    const updates = parseResult.data;

    const allPersons = await this.repository.getAllPersons(true);
    const allRelationships = await this.repository.getAllRelationships();
    const version = await this.repository.getVersion();

    const relIndex = allRelationships.findIndex((r) => r.id === id);
    if (relIndex === -1) {
      throw new NotFoundError('RELATIONSHIP_NOT_FOUND', `Relationship with ID "${id}" was not found.`);
    }

    const existing = allRelationships[relIndex];

    if (existing.relationship_type === 'spouse' && updates.parent_type !== undefined && updates.parent_type !== null) {
      throw new ValidationError('INVALID_UPDATE', 'Spouse relationships cannot have a parent_type.');
    }

    if (existing.relationship_type === 'parent' && updates.parent_type === null) {
      throw new ValidationError('INVALID_UPDATE', 'Parent relationships must specify a valid parent_type.');
    }

    const updatedRel: Relationship = {
      ...existing,
      parent_type: updates.parent_type !== undefined ? updates.parent_type : existing.parent_type,
      start_date: updates.start_date !== undefined ? updates.start_date : existing.start_date,
      end_date: updates.end_date !== undefined ? updates.end_date : existing.end_date,
      notes: updates.notes !== undefined ? updates.notes : existing.notes,
    };

    const newRels = [...allRelationships];
    newRels[relIndex] = updatedRel;

    try {
      await this.repository.saveFamilyData(allPersons, newRels, version);
    } catch (err: any) {
      if (err instanceof FamilyValidationError) {
        throw new ConflictError(err.code, err.message, err.details);
      }
      throw err;
    }

    return updatedRel;
  }

  /**
   * Deletes a relationship record without modifying either connected person.
   */
  async deleteRelationship(id: string): Promise<{ deleted: true; id: string }> {
    if (!UUID_REGEX.test(id)) {
      throw new ValidationError('INVALID_UUID', `Relationship ID "${id}" is not a valid UUID.`);
    }

    const allPersons = await this.repository.getAllPersons(true);
    const allRelationships = await this.repository.getAllRelationships();
    const version = await this.repository.getVersion();

    const exists = allRelationships.some((r) => r.id === id);
    if (!exists) {
      throw new NotFoundError('RELATIONSHIP_NOT_FOUND', `Relationship with ID "${id}" was not found.`);
    }

    const newRels = allRelationships.filter((r) => r.id !== id);

    // Persist with allPersons completely untouched
    try {
      await this.repository.saveFamilyData(allPersons, newRels, version);
    } catch (err: any) {
      if (err instanceof FamilyValidationError) {
        throw new ConflictError(err.code, err.message, err.details);
      }
      throw err;
    }

    return { deleted: true, id };
  }
}

